function readCookie(name) {
  if (typeof document === 'undefined') return '';
  const cookies = document.cookie.split(';').map((cookie) => cookie.trim());
  for (const cookie of cookies) {
    if (cookie.startsWith(`${name}=`)) {
      return decodeURIComponent(cookie.slice(name.length + 1));
    }
  }
  return '';
}

export function getInitialLocale() {
  const stored = (() => {
    if (typeof localStorage === 'undefined') return '';
    try {
      return localStorage.getItem(LOCALE_STORAGE_KEY) || '';
    } catch (error) {
      return '';
    }
  })();

  const cookieLocale = readCookie('language');
  const browserLocale =
    typeof navigator !== 'undefined' ? (navigator.language || '').slice(0, 2) : '';
  const candidate = stored || cookieLocale || browserLocale || 'en';

  const supported = SUPPORTED_LANGUAGES.find((lang) => lang.code === candidate);
  return supported ? candidate : 'en';
}

export function applyLocale(locale) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    document.documentElement.dir = RTL_LANGUAGES.has(locale) ? 'rtl' : 'ltr';
    document.cookie = `language=${encodeURIComponent(locale)}; path=/; max-age=31536000; samesite=lax`;
  }
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    }
  } catch (error) {
    // ignore storage errors
  }
}

export function translate(locale, text, params = {}) {
  const dictionary = TRANSLATIONS[locale] || {};
  let output = dictionary[text] || text;
  Object.entries(params).forEach(([key, value]) => {
    output = output.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value));
  });
  return output;
}

export function isRtl(locale) {
  return RTL_LANGUAGES.has(locale);
}
